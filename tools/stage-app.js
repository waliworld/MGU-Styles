#!/usr/bin/env node
'use strict';
/*
 * Stages the iDrive app the MGU Store builds on the head unit.
 *
 *   node tools/stage-app.js           write apps/<id>/
 *   node tools/stage-app.js --check   fail if apps/<id>/ is out of date
 *
 * The kit's builder (kit/tools/build.py) ships only the top-level .js files
 * of apps/<id>/ - no folders, no .json, no .gz. So the nested src/ is
 * flattened here with its requires rewritten, the glyph atlas is embedded in
 * atlas_data.js, and the manifest's "signals" are filled from
 * src/car/vehicle.js so there is one list, not two.
 *
 * apps/<id>/ is committed: a Store "repo tree" source builds from what is in
 * the repository. --check (run by npm test) keeps it from drifting.
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const ROOT = path.resolve(__dirname, '..');
const base = JSON.parse(fs.readFileSync(path.join(ROOT, 'app', 'app.base.json'), 'utf8'));
const ID = base.id;
const OUT = path.join(ROOT, 'apps', ID);

/* source -> name in the package */
const MODULES = [
    ['src/geometry/panel.js', 'panel.js'],
    ['src/engine/text.js', 'text.js'],
    ['src/engine/state.js', 'state.js'],
    ['src/shaders/prelude.js', 'shaders_prelude.js'],
    ['src/shaders/core.js', 'shaders_core.js'],
    ['src/shaders/parts.js', 'shaders_parts.js'],
    ['src/shaders/dial.js', 'shaders_dial.js'],
    ['src/theme/palette.js', 'palette.js'],
    ['src/theme/guide.js', 'guide.js'],
    ['src/theme/mgeom.js', 'mgeom.js'],
    ['src/shaders/mcluster.js', 'shaders_m.js'],
    ['src/theme/textlayers.js', 'textlayers.js'],
    ['src/theme/lambo.js', 'theme_toro.js'],
    ['src/theme/track.js', 'theme_track.js'],
    ['src/theme/overlays.js', 'overlays.js'],
    ['src/theme/index.js', 'theme.js'],
    ['src/car/cluster.js', 'cluster.js'],
    ['src/car/centre.js', 'centre.js'],
    ['src/car/feed.js', 'feed.js'],
    ['src/car/message.js', 'message.js'],
    ['src/car/vehicle.js', 'vehicle.js'],
    ['src/car/main.js', 'service.js'],
    ['src/car/cluster_render_client.js', 'cluster_render_client.js'],
    /* the package's own atlas loader stands in for the repository's */
    ['app/atlas.staged.js', 'atlas.js', 'src/car/atlas.js'],
    ['app/entry.js', 'main.js']
];
const FLAT = {};
MODULES.forEach((m) => { FLAT[path.join(ROOT, m[2] || m[0])] = m[1]; });

const HEADER = '// Generated by tools/stage-app.js from %s - edit that file, not this one.\n';

function rewrite(src, from) {
    return src.replace(/require\((['"])(\.{1,2}\/[^'"]+)\1\)/g, (all, q, rel) => {
        let abs = path.resolve(path.dirname(from), rel);
        if (!/\.js$/.test(abs) && fs.existsSync(abs + '.js')) abs += '.js';
        if (FLAT[abs]) return 'require(' + q + './' + FLAT[abs] + q + ')';
        /* kit modules, the generated data, and files written in package
           terms (app/entry.js names ./service.js) stay as they are */
        if (/^\.\/(kit\/|atlas_data)/.test(rel)) return all;
        const flatNames = MODULES.map((m) => './' + m[1]);
        if (flatNames.indexOf(rel) >= 0 || flatNames.indexOf(rel + '.js') >= 0) return all;
        throw new Error(path.relative(ROOT, from) + ': require(' + rel + ') has no place in the package');
    });
}

function files() {
    const out = {};
    MODULES.forEach(([src, name]) => {
        const file = path.join(ROOT, src);
        out[name] = HEADER.replace('%s', src) + rewrite(fs.readFileSync(file, 'utf8'), file);
    });

    /* The atlas, embedded: the same bytes as assets/fonts, nothing re-baked. */
    const meta = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets/fonts/atlas.json'), 'utf8'));
    const gz = fs.readFileSync(path.join(ROOT, 'assets/fonts/atlas.r8.gz'));
    zlib.gunzipSync(gz);                                   /* refuse a broken atlas here, not in the car */
    out['atlas_data.js'] = HEADER.replace('%s', 'assets/fonts/atlas.{json,r8.gz}') +
        "'use strict';\n/* The SDF glyph atlas: metrics, and the r8 bytes gzipped as base64. */\n" +
        'module.exports = {\n    meta: ' + JSON.stringify(meta) +
        ',\n    r8gz: ' + JSON.stringify(gz.toString('base64')) + '\n};\n';

    /* The manifest, its signals from the one list the service reads. */
    const Vehicle = require(path.join(ROOT, 'src/car/vehicle.js'));
    const spec = JSON.parse(JSON.stringify(base));
    spec.signals = Vehicle.SIGNALS;
    out['app.json'] = JSON.stringify(spec, null, 2) + '\n';

    out['NOTICE'] = fs.readFileSync(path.join(ROOT, 'app', 'NOTICE'), 'utf8');
    return out;
}

function binaries() {
    return { 'icon.png': fs.readFileSync(path.join(ROOT, 'app', 'icon.png')) };
}

function main() {
    const check = process.argv.indexOf('--check') >= 0;
    const want = files();
    const bins = binaries();
    if (check) {
        const stale = [];
        Object.keys(want).forEach((n) => {
            const p = path.join(OUT, n);
            if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== want[n]) stale.push(n);
        });
        Object.keys(bins).forEach((n) => {
            const p = path.join(OUT, n);
            if (!fs.existsSync(p) || !fs.readFileSync(p).equals(bins[n])) stale.push(n);
        });
        const extra = fs.existsSync(OUT) ? fs.readdirSync(OUT).filter((n) => !(n in want) && !(n in bins)) : [];
        if (stale.length || extra.length) {
            console.error('apps/' + ID + ' is out of date: ' + stale.concat(extra).join(', ') +
                '\nrun: node tools/stage-app.js');
            process.exit(1);
        }
        console.log('apps/' + ID + ' is up to date (' + (Object.keys(want).length + 1) + ' files)');
        return;
    }
    fs.rmSync ? fs.rmSync(OUT, { recursive: true, force: true }) : null;
    fs.mkdirSync(OUT, { recursive: true });
    Object.keys(want).forEach((n) => fs.writeFileSync(path.join(OUT, n), want[n]));
    Object.keys(bins).forEach((n) => fs.writeFileSync(path.join(OUT, n), bins[n]));
    const size = fs.readdirSync(OUT).reduce((s, n) => s + fs.statSync(path.join(OUT, n)).size, 0);
    console.log('staged apps/' + ID + ': ' + fs.readdirSync(OUT).length + ' files, ' +
        Math.round(size / 1024) + ' KB');
}

main();
